export const DIRS = { he: 'rtl', en: 'ltr' };

const LangCtx = createContext(null);

export function LangProvider({ children }) {
  const [lang, setLang] = useState(() => {
    const v = localStorage.getItem('chavruta-lang');
    return v === 'en' ? 'en' : 'he';
  });
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = DIRS[lang];
    document.title = STR[lang].metaTitle;
    localStorage.setItem('chavruta-lang', lang);
  }, [lang]);
  const t = (key, vars) => {
    let s = STR[lang][key] ?? STR.he[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
  return <LangCtx.Provider value={{ lang, setLang, t }}>{children}</LangCtx.Provider>;
}

export function useLang() { return useContext(LangCtx); }

// Localized labels for stored enum/topic values.
export function useLabels() {
  const { lang } = useLang();
  return {
    topic: (v) => (lang === 'en' ? TOPIC_EN[v] || v : v),
    level: (k) => LEVELS[lang][k] || k,
    mode: (k) => MODES[lang][k] || k,
    day: (k) => DAYS[lang][k] || k,
    status: (k) => STATUS[lang][k] || k,
    contactKind: (k) => CONTACT_KINDS[lang][k] || k,
    gender: (k) => GENDERS[lang][k] || k,
  };
}

export function errText(t, err) {
  return t(`err_${err?.code}`) !== `err_${err?.code}` ? t(`err_${err?.code}`) : t('err_fallback');
}
